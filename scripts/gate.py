def _arm_lint() -> int:
    return _run(_python("-m", "ruff", "check", "src/", "scripts/", "tests/"))


def _arm_format() -> int:
    return _run(_python("-m", "ruff", "format", "--check", "src/", "scripts/", "tests/"))


def _arm_types() -> int:
    return _run(_python("-m", "mypy", "src/", "scripts/"))


def _arm_test_fast() -> int:
    return _run(_pytest("--no-cov", "-m", FAST_SELECTION))


def _arm_test_sim() -> int:
    return _run(_pytest("--no-cov", "-m", "requires_pymdp"))


def _arm_test_full() -> int:
    return _run(_pytest("-m", NON_RELEASE_SELECTION))


def _arm_slow() -> int:
    return _run(_pytest("-m", "slow"))


def _arm_build_lean() -> int:
    return _run(_python("scripts/build_lean.py"))


