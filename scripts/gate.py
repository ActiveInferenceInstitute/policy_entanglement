#!/usr/bin/env python3
"""The repository's single gate entry point.

Every gate arm is defined exactly once, here, and both the GitHub Actions
workflow (``.github/workflows/ci.yml``) and the ``make`` targets call this
script.  A contributor therefore runs the same command CI runs, and a
selection rule (marker expression, upstream pin provisioning) cannot drift
between the two.

Usage::

    uv run --no-sync python scripts/gate.py                # the `ci` arm
    uv run --no-sync python scripts/gate.py test-fast      # fast local loop
    uv run --no-sync python scripts/gate.py lint types     # several arms
    uv run --no-sync python scripts/gate.py --list         # arm catalog

Arms (all commands run with this interpreter, so ``uv run --no-sync``
selects the environment for CI and for local runs alike):

=================  =====================================================
``lint``           ``ruff check src/ scripts/ tests/``
``format``         ``ruff format --check src/ scripts/ tests/``
``types``          ``mypy src/ scripts/``
``test-fast``      pytest, ``not requires_pymdp and not slow``
``test-sim``       pytest, ``requires_pymdp`` (needs ``uv sync --group sim``)
``test-full``      pytest, ``not slow``
``slow``           pytest, ``slow`` (Lean build + MathlibProofs axiom audit)
``build-lean``     ``scripts/build_lean.py`` (lake build + hygiene budget)
``mathlib``        ``scripts/build_mathlib_proofs.py`` (release gate)
``regression``     ``scripts/regression_gate.py``
``docs``           project-wide hyperlink audit + generated-docs freshness
``gnn``            pinned upstream GNN parser conformance
``pipeline``       ``scripts/run_all.py`` (Lean budget → artifacts → regression)
``pipeline-pdf``   ``scripts/run_all.py --with-pdf``
``pipeline-serial``  ``scripts/run_all.py --serial``
``pipeline-release`` ``scripts/run_all.py --with-pdf --with-mathlib``
``pdf``            ``scripts/build_pdf.py``
``pdf-validate``   ``scripts/validate_pdf.py``
``ci``             ``lint`` + ``format`` + ``types`` + ``pipeline``
``readiness``      ``pipeline-release`` + ``pdf-validate`` + lint/format/types + report
=================  =====================================================

The ``fast`` marker expression is the repository's documented selection
(``tests/README.md``, ``tests/lean/README.md``): ``slow`` marks the Lean and
MathlibProofs builds, ``requires_pymdp`` marks the ``sim``-group surface.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
from collections.abc import Callable, Sequence
from pathlib import Path

THIS_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = THIS_DIR.parent

sys.path.insert(0, str(THIS_DIR))
from _bootstrap import ensure_project_paths  # noqa: E402

ensure_project_paths(project_root=PROJECT_ROOT)

from gnn.upstream import ENV_UPSTREAM_ROOT, UpstreamPin, load_upstream_pin  # noqa: E402

PIN_PATH = PROJECT_ROOT / "gnn" / "upstream.json"


def _gate_cache_root() -> Path:
    """Operator cache root, deliberately outside the working tree.

    A checkout parked inside the repository would be scanned as project
    content (the project-wide hyperlink audit and the folder-doc guards walk
    every ``*.md``), and would put generated bytes under the tree the gates
    certify.
    """
    explicit = os.environ.get("GATE_CACHE_DIR")
    if explicit:
        return Path(explicit).expanduser()
    base = os.environ.get("XDG_CACHE_HOME")
    return (Path(base).expanduser() if base else Path.home() / ".cache") / PROJECT_ROOT.name


GNN_CACHE = _gate_cache_root() / "gnn-upstream"
GNN_TEST = "tests/test_gnn_upstream_conformance.py"
DOCS_TESTS = (
    "tests/test_project_wide_hyperlinks.py",
    "tests/test_docs_no_stale_registry_numbers.py",
    "tests/test_generate_index.py",
)

#: Fast-loop selection: no pymdp `sim` group, no Lean/Mathlib builds.
FAST_SELECTION = "not requires_pymdp and not slow"
#: Everything that does not require a Lean toolchain build.
NON_RELEASE_SELECTION = "not slow"
#: Selection used by the pipeline's regression gate (the release probes are opt-in).
PIPELINE_PYTEST_SELECTION = "not slow"

Command = Sequence[str]


def _run(command: Command, *, env: dict[str, str] | None = None) -> int:
    """Run one gate command, echoing it and its wall time."""
    print(f"+ {' '.join(command)}", flush=True)
    started = time.monotonic()
    completed = subprocess.run(command, cwd=PROJECT_ROOT, env=env, check=False)
    print(f"  exit {completed.returncode} in {time.monotonic() - started:.1f}s", flush=True)
    return completed.returncode


def _python(*args: str) -> list[str]:
    return [sys.executable, *args]


def _pytest(*selection: str) -> list[str]:
    return _python("-m", "pytest", "-q", *selection)


# --- gnn arm -------------------------------------------------------------


def _git(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(root), *args],
        cwd=PROJECT_ROOT,
        check=False,
        capture_output=True,
        text=True,
    )


def _gnn_cache_root(pin: UpstreamPin) -> Path:
    """Gate-owned checkout for this pin; the only root this arm may write to."""
    return GNN_CACHE / f"{pin.tag}-{pin.commit[:12]}"


def _probe_parser_environment(python: Path) -> bool:
    """True when ``python`` can import the pinned parser's runtime dependencies."""
    if not python.exists():
        return False
    probe = subprocess.run(
        [str(python), "-c", "import numpy, defusedxml, psutil"],
        cwd=PROJECT_ROOT,
        check=False,
        capture_output=True,
    )
    return probe.returncode == 0


def _validate_external_checkout(root: Path, pin: UpstreamPin) -> Path:
    """Validate an operator-supplied checkout without modifying it.

    ``POLICY_ENTANGLEMENT_GNN_ROOT`` may name a checkout that belongs to another
    repository (an upstream clone or a mirror), so this arm only reads it: no
    ``git init``, fetch, checkout, remote re-point, or dependency install. A
    missing commit, moved tag, or unprepared interpreter is the operator's to
    fix, or they can unset the variable and let the gate use its own cache.
    """
    root = root.expanduser()
    if not (root / ".git").exists():
        raise SystemExit(
            f"gate gnn: {ENV_UPSTREAM_ROOT}={root} is not an existing git checkout. This arm never "
            "creates or provisions an explicitly selected checkout; unset "
            f"{ENV_UPSTREAM_ROOT} to let it fetch {pin.tag} into its own cache."
        )
    if _git(root, "cat-file", "-e", f"{pin.commit}^{{commit}}").returncode != 0:
        raise SystemExit(
            f"gate gnn: {root} does not contain the pinned commit {pin.commit} for {pin.tag}. "
            "This arm does not fetch into an explicitly selected checkout: fetch it there "
            f"yourself, or unset {ENV_UPSTREAM_ROOT} to use the gate-managed cache."
        )
    tag = _git(root, "rev-parse", f"refs/tags/{pin.tag}^{{commit}}")
    if tag.returncode == 0 and tag.stdout.strip() != pin.commit:
        raise SystemExit(
            f"gate gnn: tag {pin.tag} in {root} no longer resolves to the pinned commit "
            f"{pin.commit} (found {tag.stdout.strip()}); re-pinning is a deliberate change, "
            "not a gate fix"
        )
    python = _checkout_python(root)
    if not _probe_parser_environment(python):
        raise SystemExit(
            f"gate gnn: {root} has no usable parser interpreter ({python}). The pinned parser "
            "runs under the checkout's own virtualenv, which needs numpy, defusedxml and psutil. "
            "This arm does not install into an explicitly selected checkout; prepare it there, "
            f"or unset {ENV_UPSTREAM_ROOT} to use the gate-managed cache."
        )
    print(f"  validated operator checkout {root} (read-only: HEAD, refs, origin, venv untouched)", flush=True)
    return python


def _ensure_checkout(root: Path, pin: UpstreamPin) -> None:
    """Provision the gate-owned cache checkout; fail loudly if the tag has moved."""
    if not (root / ".git").exists():
        root.mkdir(parents=True, exist_ok=True)
        result = _git(root, "init", "--quiet")
        if result.returncode != 0:
            raise SystemExit(f"gate gnn: `git init {root}` failed: {result.stderr.strip()}")
    origin = _git(root, "remote", "get-url", "origin")
    if origin.returncode != 0:
        _git(root, "remote", "add", "origin", pin.repository)
    elif origin.stdout.strip() != pin.repository:
        _git(root, "remote", "set-url", "origin", pin.repository)

    if _git(root, "cat-file", "-e", f"{pin.commit}^{{commit}}").returncode != 0:
        print(f"+ git -C {root} fetch --depth 1 origin {pin.commit} {pin.tag}", flush=True)
        fetch = _git(
            root,
            "fetch",
            "--quiet",
            "--depth",
            "1",
            "origin",
            pin.commit,
            f"refs/tags/{pin.tag}:refs/tags/{pin.tag}",
        )
        if fetch.returncode != 0:
            raise SystemExit(
                f"gate gnn: cannot fetch {pin.tag} ({pin.commit}) from {pin.repository}:\n{fetch.stderr.strip()}"
            )

    head = _git(root, "rev-parse", "HEAD")
    if head.returncode != 0 or head.stdout.strip() != pin.commit:
        checkout = _git(root, "checkout", "--quiet", "--detach", pin.commit)
        if checkout.returncode != 0:
            raise SystemExit(f"gate gnn: cannot check out {pin.commit} in {root}:\n{checkout.stderr.strip()}")

    tag = _git(root, "rev-parse", f"refs/tags/{pin.tag}^{{commit}}")
    if tag.returncode != 0 or tag.stdout.strip() != pin.commit:
        raise SystemExit(
            f"gate gnn: tag {pin.tag} no longer resolves to the pinned commit "
            f"{pin.commit} (found {tag.stdout.strip() or tag.stderr.strip()}); "
            "re-pinning is a deliberate change, not a gate fix"
        )


def _checkout_python(root: Path) -> Path:
    venv = root / ".venv"
    return venv / ("Scripts/python.exe" if os.name == "nt" else "bin/python")


def _ensure_parser_environment(root: Path) -> Path:
    """Give the gate-owned checkout an interpreter that can run the pinned parser."""
    python = _checkout_python(root)
    if _probe_parser_environment(python):
        return python
    version = os.environ.get("GATE_GNN_PYTHON", "3.12")
    if not python.exists() and _run(["uv", "venv", "--python", version, str(root / ".venv")]) != 0:
        raise SystemExit("gate gnn: cannot create the pinned checkout's virtualenv")
    install = _run(
        [
            "uv",
            "pip",
            "install",
            "--python",
            str(python),
            "numpy",
            "defusedxml",
            "psutil",
        ]
    )
    if install != 0:
        raise SystemExit("gate gnn: cannot install the pinned parser's dependencies")
    return python


def _validate_pointer(path: Path, pin: UpstreamPin) -> None:
    """Interim GNN-FEP drift check while the pinned release lacks the shared reader."""
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise SystemExit(f"gate gnn: pointer-missing: {path}") from exc
    except (OSError, UnicodeError) as exc:
        raise SystemExit(f"gate gnn: pointer-unreadable: {path}: {exc}") from exc
    required = {
        "pointer-pin-unnamed": PIN_PATH.relative_to(PROJECT_ROOT).as_posix(),
        "pointer-workflow-unnamed": "ci.yml",
        "pointer-job-unnamed": "gnn-conformance",
    }
    missing = [code for code, fact in required.items() if fact not in text]
    if pin.commit not in text and pin.commit[:12] not in text:
        missing.append("pointer-revision-unnamed")
    if missing:
        raise SystemExit(f"gate gnn: {path}: {', '.join(missing)}")
    print("gnn pin/pointer drift check: ok (local reader; shared-reader cutover pending)", flush=True)


def _arm_gnn() -> int:
    pin = load_upstream_pin(PIN_PATH)
    _validate_pointer(PROJECT_ROOT / ".github" / "GNN.md", pin)
    explicit = os.environ.get(ENV_UPSTREAM_ROOT)
    if explicit:
        # Another repository's checkout: validate only, never provision it.
        root = Path(explicit)
        _validate_external_checkout(root, pin)
    else:
        root = _gnn_cache_root(pin)
        _ensure_checkout(root, pin)
        _ensure_parser_environment(root)
    env = dict(os.environ)
    env[ENV_UPSTREAM_ROOT] = str(root)
    # The conformance test reads the pin and the shipped specs only; the
    # generated artifact tree is irrelevant, so skip the session bootstrap.
    env["ACTINF_SKIP_BOOTSTRAP"] = "1"
    status = _run(_pytest(GNN_TEST), env=env)
    version = pin.tag.removeprefix("v")
    print(f"gnn-version={version} commit={pin.commit} root={root}", flush=True)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as handle:
            handle.write(f"gnn-version={version} commit={pin.commit}\n")
    return status


